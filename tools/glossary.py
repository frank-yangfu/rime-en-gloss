def refine_char(ch, gloss):
    """Final say for a single character.

    WORD is consulted as well as SINGLE: it is easy to add an entry to the
    wrong table, and silently ignoring it is a nasty trap.
    """
    if ch in DROP:
        return None
    if ch in SINGLE:
        return SINGLE[ch]
    if ch in WORD:
        return WORD[ch]
    if ch in _LEGACY:
        return _LEGACY[ch]
    if gloss is None:
        return None
    low = gloss.lower()
    noisy = any(bad in low for bad in BAD_DEF)
    if noisy:
        if ch in SURN:
            return "(surname %s)" % SURN[ch]
        return None
    return gloss


def refine_word(word, gloss):
    """Final say for a multi-character word."""
    if word in DROP_WORDS:
        return None
    if word in WORD:
        return WORD[word]
    if word in SINGLE:
        return SINGLE[word]
    if word in _LEGACY:
        return _LEGACY[word]
    if gloss is None:
        return None
    low = gloss.lower()
    if any(bad in low for bad in BAD_DEF):
        return None
    return gloss
