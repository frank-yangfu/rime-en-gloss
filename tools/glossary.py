def _sanitize(table):
    """Remove stray CJK characters / empty glosses left by editing slips."""
    out = {}
    for key, value in table.items():
        if not key.strip() or not value:
            continue
        cleaned = re.sub(r"[\u4e00-\u9fff]+", " ", value)
        cleaned = re.sub(r"\s+", " ", cleaned).strip(" ;,/")
        if cleaned:
            out[key] = cleaned
    return out


