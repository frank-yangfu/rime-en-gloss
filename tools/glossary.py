"""Hand-checked glossary and a smarter CC-CEDICT sense picker.

Why this file exists
--------------------
CC-CEDICT is a *reading* dictionary: for many characters the first sense is a
classical, dialectal or rare-pronunciation meaning (打 -> "dozen", 吧 -> "bar",
告诉 -> "to press charges"), and 3,072 entries are nothing but "variant of X".
Taking the first entry verbatim therefore produced visibly wrong English.

This module fixes that with four layers:
  1. resolve "variant of" chains to the entry that actually carries a meaning
  2. score every candidate sense with a common-English word list and keep the
     most everyday one that is also the shortest
  3. apply a hand-checked override table for the characters and words people
     actually type (see SINGLE / WORD below)
  4. drop anything that still looks like dictionary noise
"""

